export function getRescueRank(points: number): { nameTr: string; color: string; nextPts: number } {
  if (points >= 1200) return { nameTr: 'Efsanevi Zümrüt Rütbe', color: '#34D399', nextPts: 1200 };
  if (points >= 700) return { nameTr: 'Altın Kurtarma Rütbesi', color: '#FBBF24', nextPts: 1200 };
  if (points >= 350) return { nameTr: 'Gümüş Kurtarma Rütbesi', color: '#E2E8F0', nextPts: 700 };
  if (points >= 120) return { nameTr: 'Bronz Kurtarma Rütbesi', color: '#F97316', nextPts: 350 };
  return { nameTr: 'Çaylak Kurtarma Rütbesi', color: '#94A3B8', nextPts: 120 };
}
